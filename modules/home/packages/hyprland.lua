-- Hyprland Lua config, migrated from the hyprlang settings that used to live
-- in modules/desktop/hyprland.nix and hosts/wotan/desktop-config.nix
-- (Hyprland 0.56 moved to Lua as the config format it looks for first).
--
-- Dispatcher/field names below were verified against the Hyprland source at
-- the pinned commit (src/config/lua/bindings/LuaBindingsDispatchers.cpp and
-- LuaBindingsConfigRules.cpp), not guessed from docs -- the wiki is
-- JS-rendered and wasn't fetchable.
--
-- This file is the sole Hyprland config: there is no hyprlang fallback any
-- more, nothing generates /etc/xdg/hypr/hyprland.conf and there is no
-- ~/.config/hypr/hyprland.conf. That makes parse errors here loud in effect
-- but silent in the log: if this file fails to load, Hyprland just drops a
-- brand-new example config and comes up with it, which is what previously
-- lost kb_layout and the monitor order.

