-- host.lua is generated by modules/home/packages/hyprland-configs.nix
-- from the desktop.hyprland-configs.monitors and
-- desktop.hyprland-configs.workspaces options. It holds the monitor layout
-- and the workspace-to-monitor rules, which are per-host and must not be
-- hardcoded in this shared file. `hl` and its functions stay visible inside
-- the loaded chunk.
--
-- Loaded via loadfile rather than dofile on purpose: dofile raises on a
-- missing file, which would abort this whole config and land us on Hyprland's
-- example config -- the exact silent breakage described above. Degrading to
-- "monitors on autodetect" instead leaves a screen you can actually read the
-- notification on.
local hostPath = (os.getenv("XDG_CONFIG_HOME") or (os.getenv("HOME") .. "/.config")) .. "/hypr/host.lua"
local hostChunk, hostErr = loadfile(hostPath)
if hostChunk then
    hostChunk()
else
    hl.notification.create({
        text = "hyprland.lua: could not load " .. hostPath .. " -- monitors and workspace rules are NOT applied (" .. tostring(hostErr) .. ")",
        time = 15000,
    })
end

-- plugins.lua is generated the same way: hl.plugin.load calls with the
-- nix-store paths of the plugins listed (and explained, including how to add
-- one) in modules/home/packages/hyprland-configs.nix. Their
-- configuration is in the PLUGINS section at the end of this file.
local pluginsPath = (os.getenv("XDG_CONFIG_HOME") or (os.getenv("HOME") .. "/.config")) .. "/hypr/plugins.lua"
local pluginsChunk, pluginsErr = loadfile(pluginsPath)
if pluginsChunk then
    pluginsChunk()
else
    hl.notification.create({
        text = "hyprland.lua: could not load " .. pluginsPath .. " -- plugins are NOT loaded (" .. tostring(pluginsErr) .. ")",
        time = 15000,
    })
end

